UNIT_RE = re.compile(r"\(\s*(?:원화\s*)?단위\s*:\s*([^)]+)\)")
UNIT_MULT = {"원": 1, "천원": 1_000, "백만원": 1_000_000, "십억원": 1_000_000_000}


def unit_of(text: str) -> int | None:
    """'(단위: 천원)'·'(원화단위: 천원, 외화단위: USD)' → 배수. 못 찾으면 None."""
    m = UNIT_RE.search(text)
    if not m:
        return None
    for token in norm(m.group(1)).replace("：", ":").split(","):
        u = UNIT_MULT.get(token.split(":")[-1])
        if u:
            return u
    return None

